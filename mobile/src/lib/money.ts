/**
 * Деньги на экране.
 *
 * <h2>Почему своя функция, а не `toLocaleString`</h2>
 * Поддержка `Intl` в Hermes зависит от сборки: «работает у меня» здесь
 * означало бы `49999` без разрядов — или пустую строку — на чужом
 * телефоне. Та же причина, по которой даты форматируются вручную в
 * `features/profile/api`.
 *
 * <h2>Разряды — пробелом</h2>
 * Так пишут суммы в Узбекистане: «49 999 so'm». Запятая читалась бы как
 * десятичный разделитель, точка — как тысячи «по-европейски», и обе
 * заставляли бы человека перечитывать цену.
 *
 * ⚠️ Дробная часть отбрасывается. Бэкенд хранит `BigDecimal(12,2)`, но
 * тийины в ценах платформы не используются (24 000 / 49 999 / 99 000),
 * и «49 999,00» на карточке тарифа — лишний шум.
 *
 * ⚠️ Раньше эта же функция жила под именем `groupDigits` в трёх файлах —
 * `profile.tsx`, `WatchDetail.tsx` и `EpisodeList.tsx`. Копии сведены сюда:
 * разойдясь, они дали бы одну и ту же сумму в двух написаниях на соседних
 * экранах, и заметить это можно было бы только глазами.
 */
export function formatSum(amount: number): string {
  return String(Math.round(amount)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}
