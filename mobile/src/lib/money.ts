/**
 * Деньги на экране.
 *
 * <h2>Почему своя функция, а не `toLocaleString`</h2>
 * Поддержка `Intl` в Hermes зависит от сборки: «работает у меня» здесь
 * означало бы `49999` без разрядов — или пустую строку — на чужом
 * телефоне. Та же причина, по которой даты форматируются вручную в
 * `features/profile/api`.
 *
 * <h2>Разряды — пробелом</h2>
 * Так пишут суммы в Узбекистане: «49 999 so'm». Запятая читалась бы как
 * десятичный разделитель, точка — как тысячи «по-европейски», и обе
 * заставляли бы человека перечитывать цену.
 *
 * ⚠️ Дробная часть отбрасывается. Бэкенд хранит `BigDecimal(12,2)`, но
 * тийины в ценах платформы не используются (24 000 / 49 999 / 99 000),
 * и «49 999,00» на карточке тарифа — лишний шум.
 *
 * ⚠️ Раньше эта же функция жила под именем `groupDigits` в трёх файлах —
 * `profile.tsx`, `WatchDetail.tsx` и `EpisodeList.tsx`. Копии сведены сюда:
 * разойдясь, они дали бы одну и ту же сумму в двух написаниях на соседних
 * экранах, и заметить это можно было бы только глазами.
 */
export function formatSum(amount: number): string {
  return groupDigits(amount);
}

/**
 * То же разбиение по разрядам, но не про деньги: просмотры, лайки.
 *
 * ⚠️ Отдельное имя, а не `formatSum` в чужом контексте: «12 345» под
 * глазом — это счётчик, и читать в коде `formatSum(views)` пришлось бы
 * дважды. Правило одно и лежит в одном месте — ровно то, ради чего копии
 * и сводились сюда.
 *
 * ⚠️ Сокращения («1.2k») здесь нет: это соседняя функция `compactCount`,
 * и выбор между ними делает вызывающий. Разбор — там же.
 */
export function groupDigits(value: number): string {
  return String(Math.round(value)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

/**
 * Счётчик, который обязан помещаться: «1.2k», «1.5m».
 *
 * <h2>Почему это появилось</h2>
 * Заказчик (14.09.2026): «view larni uzun bo'lib ketsa 1.2k 1.5m qilib
 * ber». Число стоит НА обложке, в плашке шириной в треть карточки, и
 * рядом с ним нет места: «1 234 567» в ряду из трёх карточек занимало
 * половину кадра.
 *
 * ⚠️ Раньше в этом файле было написано обратное — «округления до 12K нет
 * намеренно, сокращение врёт в мелочах». Довод верный и остаётся верным:
 * 1 500 и 1 549 действительно становятся одним «1.5k». Но решает не он:
 * на витрине важно «много», а не «сколько именно», и точная цифра никуда
 * не делась — она в `groupDigits` и стоит там, где на неё смотрят
 * осознанно (донаты, баланс, суммы).
 *
 * <h2>Правила</h2>
 *   - меньше тысячи — как есть: «999», «35». Сокращать нечего;
 *   - дальше — «1.2k», «12k», «123k», «1.5m». Дробная часть только пока
 *     целая однозначна: «12.3k» шире «12k» на два знака и ничего не
 *     добавляет;
 *   - округление ВНИЗ. «2k» на 1 999 просмотрах — приписка, которой не
 *     было; «1.9k» — правда с точностью до сотни.
 */
const COMPACT_UNITS = [
  { limit: 1e9, suffix: 'b' },
  { limit: 1e6, suffix: 'm' },
  { limit: 1e3, suffix: 'k' },
] as const;

export function compactCount(value: number): string {
  const count = Math.round(value);
  const unit = COMPACT_UNITS.find((u) => count >= u.limit);

  // Отрицательных счётчиков не бывает, но и врать про них нечего:
  // маленькие числа уходят в обычное разбиение по разрядам.
  if (unit === undefined) return groupDigits(count);

  const scaled = count / unit.limit;
  // `floor`, а не `toFixed`: `toFixed` округляет, и 1 999 стало бы «2.0k».
  const short =
    scaled < 10 ? (Math.floor(scaled * 10) / 10).toFixed(1).replace(/\.0$/, '') : String(Math.floor(scaled));

  return short + unit.suffix;
}
