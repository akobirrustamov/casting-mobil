import { LOGO_PATHS, LOGO_VIEWBOX } from './logoPaths';

/**
 * Трафарет знака: прямоугольник с дыркой в форме логотипа.
 *
 * На нём держится весь `BrandLoader` — см. пояснение приёма там.
 * Вынесено отдельным модулем, потому что это чистая геометрия: так её
 * проверяет тест, не поднимая React Native.
 *
 * <h2>Почему работает</h2>
 * При заливке `evenodd` точка закрашена, если луч из неё пересекает
 * нечётное число контуров. Рамка снаружи добавляет ОДНО пересечение
 * всюду внутри холста — то есть переворачивает чётность целиком:
 *
 *   фон             0 → 1   закрашен цветом подложки
 *   знак            1 → 2   дырка, сквозь неё видно движение
 *   перфорация      2 → 3   снова подложка
 *
 * Порядок контуров при этом не важен, а вложенность сохраняется — она
 * и так задана в самом SVG.
 */

/** Поле вокруг знака, в единицах viewBox. Отдано ореолу и блику. */
export const LOGO_PAD = 90;

/** Сторона холста вместе с полем. */
export const CUTOUT_VIEW = LOGO_VIEWBOX + LOGO_PAD * 2;

export const CUTOUT_VIEWBOX = `${-LOGO_PAD} ${-LOGO_PAD} ${CUTOUT_VIEW} ${CUTOUT_VIEW}`;

/**
 * Насколько рамка выходит ЗА холст.
 *
 * ⚠️ Не украшение. Ровно по краю холста сглаживание оставляет волосяную
 * щель: подложка не докрашивает последний пиксель, и сквозь него видно
 * блик — по правому и нижнему краю знака проступает светлая рамка.
 * Лишнее всё равно обрезается по viewBox, так что запас бесплатен.
 */
const FRAME_OVERHANG = LOGO_PAD;

const FRAME_MIN = -(LOGO_PAD + FRAME_OVERHANG);
const FRAME_MAX = LOGO_VIEWBOX + LOGO_PAD + FRAME_OVERHANG;

/**
 * Рамка, а следом — все контуры знака.
 *
 * ⚠️ Рисовать ТОЛЬКО с `fillRule="evenodd"`. С `nonzero` рамка закрасит
 * холст целиком и знак пропадёт.
 */
export const CUTOUT = [
  `M${FRAME_MIN},${FRAME_MIN} ` +
    `L${FRAME_MAX},${FRAME_MIN} ` +
    `L${FRAME_MAX},${FRAME_MAX} ` +
    `L${FRAME_MIN},${FRAME_MAX} Z`,
  ...LOGO_PATHS,
].join(' ');
