import { Ionicons } from '@expo/vector-icons';
import type { ReactNode } from 'react';
import {
  KeyboardAvoidingView,
  Platform,
  Pressable,
  ScrollView,
  View,
  useWindowDimensions,
} from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { Button } from '@/components/ui/Button';
import { FormMessage } from '@/components/ui/FormMessage';
import { GlowBackdrop } from '@/components/ui/GlowBackdrop';
import { Wordmark } from '@/components/ui/Wordmark';
import { TOUCH_TARGET, colors } from '@/theme/tokens';

import { AuthLanguageButton } from './AuthLanguageButton';

/**
 * Общая раскладка трёх экранов входа: вход/регистрация, SMS-код,
 * имя и пароль.
 *
 * <h2>Зачем один каркас на три экрана</h2>
 * Заказчик (03.09.2026): «sms kod kiritishi, ism familiya kiritish
 * qismini ham bir xil qimirlamaydigan qil». Раньше каждый экран
 * складывал ярусы сам, и колонка полей стояла на разной высоте:
 *
 * • на входе знак начинался сразу под статус-баром, а на коде и пароле
 *   его сдвигала вниз строка со стрелкой «назад» — почти на её высоту;
 * • середина центрировалась (`justifyContent: 'center'`), поэтому
 *   высота полей задавала их же положение: три поля на пароле стояли
 *   выше, чем одно поле кода.
 *
 * Человек шёл «номер → код → имя и пароль», и поле каждый раз оказывалось
 * в новом месте — приходилось искать его глазами и переносить палец.
 *
 * <h2>Как стоит теперь</h2>
 * Ярусы жёсткие и одинаковые на всех трёх экранах:
 *
 * 1. знак — сразу под статус-баром и В ПОТОКЕ прокрутки (уезжает вместе
 *    с формой); стрелка «назад» лежит ПОВЕРХ и ничего не двигает;
 * 2. шапка — в слоте {@link HEADER_HEIGHT} фиксированной высоты, поэтому
 *    первое поле начинается на одной и той же высоте везде: и там, где
 *    шапка это переключатель разделов, и там, где это заголовок с
 *    подписью;
 * 3. поля — сразу под шапкой, ПРИЖАТЫ ВВЕРХ, а не по центру;
 * 4. нижняя группа (`footer`) — сразу под полями, а НЕ у нижнего края;
 * 5. распорка — единственное, что меняет высоту, и стоит она ПОСЛЕ
 *    нижней группы: весь запас высоты уходит под неё, а не в середину
 *    формы (07.09.2026 — до этого на высоком экране между полем и
 *    «yoki» зияло ~400 пунктов пустоты);
 * 6. согласие (`legal`) — прижато к НИЗУ прокрутки, вплотную над кнопкой;
 * 7. сообщение и главная кнопка — вне прокрутки, всегда на виду, место
 *    под сообщение забронировано (см. `FormMessage`).
 *
 * ⚠️ Вне прокрутки осталась ТОЛЬКО главная кнопка: что нажать — видно
 * всегда, даже с открытой клавиатурой. Знак прокручивается вместе с
 * формой и на низком экране просто уходит наверх, освобождая место
 * полям.
 *
 * <h2>Почему пустого места почти не осталось</h2>
 * Заказчик (09.09.2026) прислал экран входа со словами «shunday to'lib
 * tushsin, hozir orasi ancha ochiq qolgan»: форма должна стоять плотно,
 * без разрыва.
 *
 * Один разрыв 07.09 уже закрыли — распорку убрали из середины. Но
 * остаток высоты просто переехал вниз: на высоком телефоне между
 * строкой согласия и кнопкой оставалось за сотню пунктов пустоты, а
 * знак при этом стоял мелкий (92 при 150 на референсе). Экран был
 * заполнен сверху на треть и пуст снизу на треть.
 *
 * Теперь остаток идёт ЗНАКУ, а не пустоте:
 *
 * • строка согласия ушла в слот `legal` и прижата к низу прокрутки —
 *   она стоит вплотную над кнопкой, как на референсе;
 * • знак берёт ровно ту высоту, которая осталась от формы
 *   ({@link markSizeFor}), и на высоком экране дорастает до
 *   референсных 150–168.
 */

/**
 * Высота слота шапки.
 *
 * Считана по самой высокой из трёх шапок: 26 (`h2` в одну строку) +
 * 8 (`gap-2`) + 36 (две строки `caption` — длинные русские
 * `phoneSubtitle` и `nameSubtitle` на узком экране переносятся).
 *
 * ⚠️ Было 104 — по переключателю разделов «Kirish / Ro'yxatdan o'tish»,
 * которого на экране нет с 04.09. Слот пережил свою причину и держал
 * полсотни пунктов пустоты под каждым заголовком.
 *
 * ⚠️ Меняешь тут — проверь ВСЕ ТРИ экрана: смысл числа в том, что оно
 * одно на всех, а не в самом значении.
 */
export const HEADER_HEIGHT = 70;

/**
 * Пределы знака.
 *
 * Верхний — с референса (150 при ширине экрана 375), с запасом на
 * широкие телефоны. Нижний — граница, за которой знак перестаёт быть
 * знаком и становится иконкой.
 */
const MARK_MIN = 88;
const MARK_MAX = 168;

/** Ширина знака относительно ширины экрана. По референсу: 150 из 375. */
const MARK_WIDTH_RATIO = 0.4;

/**
 * Сколько на самом плотном из трёх экранов входа занимает всё, кроме
 * блока со знаком. Плотнее всех — вход: под полем ещё и Google, и
 * согласие.
 *
 *   поля     8 (`pt-2`) + 70 (шапка) + 16 (`gap-4`) + 66 (карточка) = 160
 *   низ      24 (`pt-6`) + 32 («yoki») + 16 + 99 (Google) + 8       = 179
 *   распорка 16 (минимум)                                           =  16
 *   согласие 36 (две строки `caption`) + 4                          =  40
 *   кнопка   12 + 36 (место под ошибку) + 12 + 45 + 12              = 117
 *
 * Считано по самому длинному переводу. Ошибиться в бо́льшую сторону не
 * страшно — знак получит на пару пунктов меньше, чем мог бы; в
 * меньшую — экран поедет в прокрутку.
 */
const CHROME_HEIGHT = 512;

/**
 * Блок «знак + название + слоган + черта» выше самого знака во столько
 * раз плюс столько постоянного.
 *
 * Разбор высот — в `Wordmark`: название `0.31×` кегля (строка ≈ `0.37×`
 * знака), слоган `0.088×` (строка ≈ `0.11×`), между ярусами 10 + 10 +
 * 16 и 4 на черту, плюс 12 отступов контейнера.
 */
const MARK_BLOCK_RATIO = 1.48;
const MARK_BLOCK_EXTRA = 52;

/**
 * Размер знака — от того, сколько высоты остаётся под него.
 *
 * ⚠️ Считается от ОКНА, а не от содержимого экрана: число обязано быть
 * одним на всех трёх шагах. Считай знак от своей колонки — и он поехал
 * бы в размере от шага к шагу, ради чего весь каркас и заводился.
 */
export function markSizeFor(freeHeight: number, width: number): number {
  const fits = Math.round(
    (freeHeight - CHROME_HEIGHT - MARK_BLOCK_EXTRA) / MARK_BLOCK_RATIO
  );
  const widest = Math.min(MARK_MAX, Math.round(width * MARK_WIDTH_RATIO));

  return Math.max(MARK_MIN, Math.min(widest, fits));
}

export function AuthScaffold({
  onBack,
  header,
  children,
  footer,
  legal,
  message,
  action,
}: {
  /** Стрелка «назад». Нет обработчика — нет и стрелки (экран входа). */
  onBack?: () => void;
  /** Переключатель разделов или заголовок с подписью — слот одной высоты. */
  header: ReactNode;
  /** Поля формы. Идут сразу под шапкой. */
  children: ReactNode;
  /** Что идёт сразу под полями: разделитель «yoki», вход через Google. */
  footer?: ReactNode;
  /**
   * Согласие с документами — единственное, что прижато к НИЗУ прокрутки.
   *
   * ⚠️ Именно отдельный слот, а не хвост `footer`: согласие относится к
   * кнопке («нажимая — соглашаешься»), а не к входу через Google, и на
   * референсе стоит вплотную над ней. Пока оно жило в `footer`, между
   * ним и кнопкой копился весь запас высоты экрана.
   */
  legal?: ReactNode;
  /** Ошибка над главной кнопкой. Место под неё занято всегда. */
  message?: string | null;
  /** Единственное главное действие экрана — по ТЗ на экране один CTA. */
  action: {
    label: string;
    onPress: () => void;
    loading?: boolean;
    disabled?: boolean;
  };
}) {
  const insets = useSafeAreaInsets();
  const { width, height } = useWindowDimensions();

  // Безопасная высота окна: полосы системы знаку не принадлежат.
  const markSize = markSizeFor(height - insets.top - insets.bottom, width);

  return (
    <KeyboardAvoidingView
      behavior={Platform.OS === 'ios' ? 'padding' : undefined}
      className="flex-1 bg-ink"
      style={{ paddingTop: insets.top }}
    >
      {/* Свечение с референса заказчика: на пустом экране входа оно и
          делает всю картинку, поэтому здесь оно ярче обычного. */}
      <GlowBackdrop intensity="hero" decor />

      {/* ⚠️ Стрелка вынута из потока намеренно. Пока она стояла строкой
          над знаком, знак и вся колонка под ним ехали вниз на её высоту —
          и экраны кода и пароля стояли ниже экрана входа. */}
      {onBack ? (
        <Pressable
          onPress={onBack}
          hitSlop={16}
          accessibilityRole="button"
          style={{ position: 'absolute', top: insets.top + 10, left: 24, zIndex: 10 }}
        >
          <Ionicons name="arrow-back" size={24} color={colors.white} />
        </Pressable>
      ) : null}

      <ScrollView
        className="flex-1"
        contentContainerStyle={{ flexGrow: 1 }}
        keyboardShouldPersistTaps="handled"
        showsVerticalScrollIndicator={false}
      >
        {/* Знак прокручивается ВМЕСТЕ с формой (заказчик, 03.09.2026:
            «login pagelarda header logolarni fixed qilma»).

            Он и правда лучше живёт в потоке: на низком экране с открытой
            клавиатурой знак уезжает вверх и отдаёт свои ~120 пунктов
            полям, вместо того чтобы занимать треть экрана над одной
            строкой ввода. На положение колонки это не влияет — она
            по-прежнему начинается сразу под знаком и одинаково на всех
            экранах входа. */}
        {/* Слоган «PLAY. WATCH. INSPIRE.» вернулся по прямому слову
            заказчика (07.09.2026): он прислал экран входа со слоганом и
            сказал делать так. Выключен он был 03.09 вместе с переездом
            на общий каркас — не по чьему-то решению, а заодно.

            Слоган включается ЗДЕСЬ, то есть сразу на всех трёх экранах
            входа: он добавляет высоты, и будь он только на первом, поле
            номера стояло бы выше поля кода — ровно то, от чего каркас и
            избавлялся. То же и с размером знака: он не константа, а
            остаток высоты, не занятый формой (`markSizeFor`), — и потому
            считается здесь, один на все три экрана. */}
        <View className="items-center pb-1 pt-2">
          <Wordmark variant="stacked" markSize={markSize} showTagline />

          {/* Шестерёнка выбора языка — справа, примерно на нижней кромке
              знака, как на референсе. Она ВНЕ потока, поэтому колонка
              под ней стоит там же, где стояла бы без неё. */}
          <AuthLanguageButton top={markSize - TOUCH_TARGET / 2} />
        </View>

        <View className="gap-4 px-6 pt-2">
          {/* Слот шапки. Содержимое стоит по центру слота, а вот его НИЗ
              всегда на одной высоте — поэтому первое поле на всех трёх
              экранах начинается в одном и том же месте. */}
          <View style={{ height: HEADER_HEIGHT, justifyContent: 'center' }}>
            {header}
          </View>

          {children}
        </View>

        {footer ? <View className="gap-4 px-6 pb-2 pt-6">{footer}</View> : null}

        {/* ⚠️ Распорка стоит ПОСЛЕ нижней группы, а не перед ней.

            Пока она была перед `footer`, весь запас высоты вываливался в
            одно место — между полем и разделителем «yoki». На высоком
            экране это ~400 пунктов пустоты посреди формы: поле висело
            в одиночестве, а «войти через Google» уезжало к самому низу,
            и экран читался как недогрузившийся.

            Теперь запас уходит вниз, под согласие: колонка «знак →
            заголовок → поле → yoki → Google → согласие» стоит плотно,
            а пустое место оказывается там, где его и ждёшь — над
            кнопкой, прижатой к нижнему краю.

            Положение поля от этого не меняется: оно по-прежнему
            ПРИЖАТО ВВЕРХ и стоит на одной высоте на всех трёх экранах —
            ради этого каркас и делался.

            ⚠️ Запас здесь теперь МАЛЕНЬКИЙ: почти всю свободную высоту
            выбирает знак (`markSizeFor`), и распорка только добирает
            остаток от округлений. */}
        <View className="flex-1" style={{ minHeight: 16 }} />

        {/* Согласие — последним в прокрутке, вплотную над кнопкой. */}
        {legal ? <View className="px-6 pb-1">{legal}</View> : null}
      </ScrollView>

      {/* Главное действие — последним и всегда на виду. */}
      <View className="gap-3 px-6 pt-3" style={{ paddingBottom: insets.bottom + 12 }}>
        {/* ⚠️ Место под сообщение занято ВСЕГДА: ошибка приходит в ответ
            на нажатие, и если бы строка раздвигала низ экрана, кнопка
            уходила бы из-под пальца ровно в момент повторного нажатия. */}
        <FormMessage message={message} />

        <Button
          variant="primary"
          shape="card"
          loading={action.loading}
          disabled={action.disabled}
          onPress={action.onPress}
          // Стрелка идёт вплотную к подписи (отступ у кнопки один — `gap`).
          // Своего `marginLeft` тут больше нет: с ним знак отъезжал к краю
          // и висел отдельно от слова, будто это две разные кнопки.
          trailing={<Ionicons name="arrow-forward" size={18} color={colors.white} />}
        >
          {action.label}
        </Button>
      </View>
    </KeyboardAvoidingView>
  );
}
