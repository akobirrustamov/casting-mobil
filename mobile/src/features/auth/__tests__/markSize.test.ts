import { markSizeFor } from '../AuthScaffold';

/**
 * Размер знака на экранах входа.
 *
 * Заказчик (09.09.2026) прислал экран входа со словами «shunday to'lib
 * tushsin, hozir orasi ancha ochiq qolgan»: форма должна стоять плотно.
 * Заполняет экран именно знак — он забирает высоту, которая осталась от
 * формы, вместо того чтобы отдавать её пустой распорке.
 *
 * ⚠️ Тест держит ГРАНИЦЫ, а не конкретные числа: числа зависят от
 * высот карточки, кнопки и слота под ошибку, и меняются вместе с ними.
 * Ломается — значит уехала граница, а не «поправь ожидание».
 *
 * Аргументы — безопасная высота окна (без системных полос) и его ширина.
 */

/** С референса: знак 150 при ширине экрана 375. */
const REFERENCE_MARK = 150;

describe('markSizeFor', () => {
  it('на высоком телефоне дорастает до референсного знака', () => {
    // Pixel-класс: 412×915, полосы 24 сверху и 48 снизу.
    expect(markSizeFor(915 - 24 - 48, 412)).toBeGreaterThanOrEqual(REFERENCE_MARK);
  });

  it('на среднем телефоне остаётся крупным знаком, а не иконкой', () => {
    // iPhone-класс: 375×812, полосы 44 и 34. Места меньше — знак
    // ужимается, но остаётся заметно крупнее прежних 92.
    const mark = markSizeFor(812 - 44 - 34, 375);

    expect(mark).toBeGreaterThan(92);
    expect(mark).toBeLessThanOrEqual(REFERENCE_MARK);
  });

  it('на низком телефоне не съедает место у формы', () => {
    // iPhone SE-класс: 667×375, полоса 20. Высоты не хватает даже форме,
    // и знак обязан отдать всё, что может.
    expect(markSizeFor(667 - 20, 375)).toBe(88);
  });

  it('не шире 40% экрана — иначе знак упирается в края', () => {
    // Высоты сколько угодно, ограничивает ширина.
    expect(markSizeFor(2000, 320)).toBe(128);
  });

  it('не растёт бесконечно на планшетной высоте', () => {
    expect(markSizeFor(2000, 1000)).toBe(168);
  });

  it('чем больше свободной высоты, тем крупнее знак', () => {
    const sizes = [600, 700, 800, 900].map((h) => markSizeFor(h, 412));

    expect(sizes).toEqual([...sizes].sort((a, b) => a - b));
  });
});
