import * as Updates from 'expo-updates';
import { Text } from 'react-native';

/**
 * Какая версия JS сейчас запущена.
 *
 * <h2>Зачем это на экране</h2>
 * Обновления по воздуху применяются НЕ СРАЗУ: первый запуск скачивает,
 * второй применяет. Пока не видно, что именно крутится на телефоне,
 * любая диагностика превращается в гадание: «ошибка не изменилась» может
 * означать и что причина другая, и что до телефона просто не доехала
 * новая сборка кода.
 *
 * `embedded` — работает бандл из APK, обновление ещё не применилось.
 * Иначе — первые 8 символов идентификатора обновления.
 *
 * ⚠️ Временно, только на время разбора входа. Убрать вместе с приписками
 * кодов ошибок.
 */
export function BuildMarker() {
  const id = Updates.isEmbeddedLaunch ? 'embedded' : (Updates.updateId ?? '—').slice(0, 8);

  return (
    <Text className="text-center text-caption text-text-muted opacity-50">{id}</Text>
  );
}
