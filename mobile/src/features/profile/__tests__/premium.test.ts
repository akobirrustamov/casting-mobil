import { formatDate, premiumState } from '../api';

/**
 * Состояние подписки на экране профиля.
 *
 * <h2>Почему это стоит теста</h2>
 * `/api/v1/app/me` описывает подписку двумя полями — `active` и `until`,
 * и в них ТРИ разных случая, а не два. Соблазн написать `active ? … : …`
 * велик, но тогда человек, у которого подписка кончилась вчера, увидит
 * ровно то же, что и никогда не плативший. Для него это разные вещи:
 * в первом случае он захочет продлить и ему нужна дата.
 *
 * Второй предмет проверки — дата. Она приходит как `LocalDateTime` без
 * зоны (`2026-09-30T17:50:49.387223`), и её нельзя гонять через `Date`:
 * поддержка `Intl` в Hermes зависит от сборки, а часовой пояс сдвинул бы
 * последний день подписки на предыдущий.
 */
describe('premiumState', () => {
  it('активная подписка', () => {
    expect(premiumState({ active: true, until: '2026-09-30T17:50:49' })).toBe('active');
  });

  it('истёкшая отличается от отсутствующей — у неё есть дата', () => {
    expect(premiumState({ active: false, until: '2026-08-28T17:50:49' })).toBe('expired');
    expect(premiumState({ active: false, until: null })).toBe('none');
  });

  it('нет ответа сервера — считаем, что подписки нет', () => {
    // Осторожная сторона: показать «Premium» без подтверждения значило бы
    // пообещать доступ, которого может не быть.
    expect(premiumState(undefined)).toBe('none');
  });

  /**
   * ⚠️ `active` приходит с сервера уже посчитанным (ТЗ §37: решение о
   * премиуме живёт в `AccessService`). Клиент НЕ сравнивает дату с
   * текущей — иначе правило существовало бы в двух местах и разъехалось
   * бы при первом же изменении тарифов.
   */
  it('дата в прошлом при active:true всё равно активна — решает сервер', () => {
    expect(premiumState({ active: true, until: '2000-01-01T00:00:00' })).toBe('active');
  });
});

describe('formatDate', () => {
  it('день, месяц, год', () => {
    expect(formatDate('2026-09-30T17:50:49.387223')).toBe('30.09.2026');
  });

  it('без срока и с мусором — пусто, а не «NaN.NaN»', () => {
    expect(formatDate(null)).toBeNull();
    expect(formatDate('')).toBeNull();
    expect(formatDate('<!doctype html>')).toBeNull();
  });

  /**
   * Часовой пояс не применяется намеренно: сервер прислал местную дату
   * окончания, и сдвиг превратил бы 30 сентября в 29-е.
   */
  it('поздний час не сдвигает день', () => {
    expect(formatDate('2026-09-30T23:59:59')).toBe('30.09.2026');
  });
});
