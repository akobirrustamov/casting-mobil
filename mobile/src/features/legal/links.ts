import * as WebBrowser from 'expo-web-browser';

/**
 * Пользовательское соглашение и политика конфиденциальности.
 *
 * <h2>⚠️ Почему адрес зашит, а не собран из `BASE_URL`</h2>
 * `BASE_URL` — это адрес API, и на стенде он выглядит как
 * `http://192.168.0.5:8099`. Юридические страницы там не лежат и лежать
 * не будут: они одни на весь продукт и живут на боевом домене.
 *
 * Собери мы адрес из `BASE_URL`, ссылка в отладочной сборке вела бы в
 * никуда — а проверять её стали бы именно там.
 *
 * <h2>Эти же адреса нужны Google</h2>
 * Экран согласия OAuth требует ссылки на условия и политику, причём на
 * том же домене, что и приложение. То есть менять их нельзя, не поменяв
 * заодно настройки в Google Cloud Console.
 */
const DOMAIN = 'https://uzcasting.com';

export const TERMS_URL = `${DOMAIN}/kelishuv`;
export const PRIVACY_URL = `${DOMAIN}/maxfiylik`;

/**
 * Открывает страницу во встроенном браузере.
 *
 * Не `Linking.openURL`: тот выкидывает человека в отдельное приложение
 * посреди регистрации, и вернуться назад он может только кнопкой
 * «назад» системы. Встроенный браузер закрывается крестиком и оставляет
 * экран входа там, где он был — с уже введённым номером.
 *
 * Ошибку глотаем намеренно: не открывшаяся справочная страница не повод
 * показывать сбой на экране входа.
 */
export async function openLegal(url: string): Promise<void> {
  try {
    await WebBrowser.openBrowserAsync(url);
  } catch {
    // Браузера нет или система отказала — вход от этого не ломается.
  }
}
