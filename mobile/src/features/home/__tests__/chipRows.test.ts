import fs from 'fs';
import path from 'path';

/**
 * Ряды кнопок-пилюль не растягиваются по высоте.
 *
 * <h2>Что тут ломается тихо</h2>
 * Внутри горизонтальной прокрутки поперечная ось — ВЕРТИКАЛЬНАЯ, и дети
 * по умолчанию растягиваются по ней. Сам ряд при коротком списке
 * забирает остаток высоты экрана. В сумме кнопка «Kliplar» становится
 * пилюлей во весь экран (видео заказчика, 10.09.2026).
 *
 * ⚠️ Заметно это только там, где карточек мало: с длинным списком
 * свободной высоты нет, и ряд выглядит нормально. Поэтому ошибка дожила
 * до демонстрации заказчику — на экране разработчика её обычно не видно.
 *
 * ⚠️ Проверяется исходник как текст. Поймать это рендером нельзя: в
 * тестовом рендерере нет раскладки, высоты не считаются, и растянутая
 * кнопка выглядит точно так же, как нормальная.
 */
const ROOT = path.join(__dirname, '../../../..');

/** Ряды пилюль: вкладки на «Media» и сезоны в списке серий. */
const ROWS = [
  { file: 'app/(tabs)/premiere.tsx', what: 'фильтры на «Media»' },
  { file: 'src/features/watch/EpisodeList.tsx', what: 'сезоны в списке серий' },
];

describe('горизонтальные ряды кнопок', () => {
  it.each(ROWS)('$what: дети не тянутся по высоте', ({ file }) => {
    const source = fs.readFileSync(path.join(ROOT, file), 'utf8');

    // Один горизонтальный ряд на файл — иначе проверку надо уточнять.
    expect(source.split('horizontal').length - 1).toBe(1);

    const centred =
      source.includes('items-center') || source.includes("alignItems: 'center'");
    expect(centred).toBe(true);
  });

  it.each(ROWS)('$what: ряд не забирает остаток высоты', ({ file }) => {
    const source = fs.readFileSync(path.join(ROOT, file), 'utf8');

    expect(source).toContain('flexGrow: 0');
  });
});
