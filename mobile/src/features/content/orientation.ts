/**
 * Формат кадра контента: обычное видео и «рилс».
 *
 * <h2>Откуда берётся</h2>
 * Из админки: у контента есть поле «Формат» (`ContentOrientation` на
 * бэкенде — `LANDSCAPE` / `VERTICAL`). Приходит в трёх ответах: карточка
 * главной, `/watch/**` и список серий.
 *
 * <h2>Почему не определяем по самому файлу</h2>
 * `player.videoTrack.size` знает настоящий размер кадра — но только после
 * загрузки видео. А у закрытого контента видео вообще не выдаётся
 * (`sources` пустой), при этом афишу рисовать надо. Плюс до загрузки кадр
 * успел бы прыгнуть из 16:9 в 9:16 у всех на глазах.
 *
 * <h2>Формат — не тип контента</h2>
 * ТЗ §13: оси независимы. Вертикальным может быть и мини-сериал, и клип,
 * и подкаст. Поэтому решение принимается по `orientation`, а не по
 * `contentType` и не по тому, из какой секции пришла карточка.
 */
export type Orientation = 'LANDSCAPE' | 'VERTICAL' | (string & {});

/**
 * Вертикальный ли кадр.
 *
 * Неизвестное и отсутствующее значение — «нет». Старая сборка бэкенда поля
 * не отдаёт, и горизонтальный плеер там честнее: он хотя бы не растянет
 * обычное видео на весь экран.
 */
export function isVertical(orientation: Orientation | null | undefined): boolean {
  return orientation === 'VERTICAL';
}

/** Отношение сторон кадра — для `aspectRatio` у контейнеров. */
export function frameRatio(orientation: Orientation | null | undefined): number {
  return isVertical(orientation) ? 9 / 16 : 16 / 9;
}

/**
 * Отношение сторон КАРТОЧКИ.
 *
 * У горизонтального контента это не 16:9: постер в каталоге — вертикальный
 * 2:3, как в мокапах и у Yangi.TV. Отличается именно рилс — он повторяет
 * форму самого видео, иначе ряд «Reels» ничем не отличался бы от обычного.
 */
export function cardRatio(orientation: Orientation | null | undefined): number {
  return isVertical(orientation) ? 9 / 16 : 2 / 3;
}

/**
 * Одна пропорция на весь ряд.
 *
 * <h2>Зачем не по каждой карточке отдельно</h2>
 * Формат — независимая ось (ТЗ §13), поэтому в «Mini seriallar» может
 * лежать и вертикальный мини-сериал, и обычный. Когда каждая карточка
 * выбирала форму сама, соседи в одном ряду выходили разной высоты:
 * подписи вставали на разных уровнях, и ряд читался как сломанный.
 *
 * Правило: ряд целиком вертикальный — 9:16, иначе обычный постер 2:3.
 * То есть «Reels seriallar» остаётся рилсами, а смешанный ряд
 * выравнивается по стандартной карточке.
 */
export function rowRatio(orientations: (Orientation | null | undefined)[]): number {
  if (orientations.length === 0) return 2 / 3;
  return orientations.every(isVertical) ? 9 / 16 : 2 / 3;
}
