const PanelI18nContext = createContext(null);

export function PanelI18nProvider({ children }) {
  const [locale, setLocaleState] = useState(
    () => localStorage.getItem(STORAGE_KEY) || 'uz'
  );

  const setLocale = useCallback((next) => {
    if (!LOCALES.includes(next)) return;
    localStorage.setItem(STORAGE_KEY, next);
    setLocaleState(next);
  }, []);

  /** t('key', {n: 5}) - kalit topilmasa kalitning o'zini qaytaradi. */
  const t = useCallback(
    (key, vars) => {
      const table = dict[locale] || dict.uz;
      let out = table[key] ?? dict.uz[key] ?? key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        });
      }
      return out;
    },
    [locale]
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <PanelI18nContext.Provider value={value}>{children}</PanelI18nContext.Provider>;
}

export function usePanelI18n() {
  const ctx = useContext(PanelI18nContext);
  if (!ctx) throw new Error('usePanelI18n faqat PanelI18nProvider ichida ishlaydi');
  return ctx;
}
